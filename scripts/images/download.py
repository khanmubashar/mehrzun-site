"""Download the chosen Pexels photos at web sizes with Playwright and write lib/images.ts."""
import json
from pathlib import Path
from playwright.sync_api import sync_playwright

SITE = Path.home() / "Desktop/mehrzun-site"
DEST = SITE / "assets/img"
meta = {v["key"]: {**v, "id": k} for k, v in json.load(open("meta.json")).items()}
# slot -> (candidate key, width, alt text)
PICKS = {
    "hero": ("005", 2400, "A shopkeeper's spice and dry-goods shop"),
    "about": ("037", 1400, "A woman running her own small shop"),
    "work": ("054", 2200, "Hands holding saffron flowers in fresh soil"),
    "donate": ("102", 2200, "A young green seedling growing from the soil"),
    "g1": ("014", 1000, "A tailor working at his sewing machine"),
    "g2": ("086", 1000, "Two women working in a tailoring workshop"),
    "g3": ("043", 1000, "A fruit seller at his stall"),
    "g4": ("072", 1000, "Hands stitching embroidery on a hoop"),
    "g5": ("046", 1000, "A flower-garland seller at the market"),
    "g6": ("010", 1000, "A shopkeeper in his clothing shop"),
    "g7": ("136", 1000, "A vegetable seller with fresh produce"),
    "g8": ("039", 1000, "A tea-stall owner at work"),
}
with sync_playwright() as p:
    b = p.chromium.launch()
    ctx = b.new_context()
    for slot, (key, w, alt) in PICKS.items():
        m = meta[key]
        r = ctx.request.get(f"{m['base']}?auto=compress&cs=tinysrgb&w={w}&fm=jpg")
        assert r.ok, (slot, r.status)
        (DEST / f"{slot}.jpg").write_bytes(r.body())
        print(slot, key, len(r.body()) // 1024, "KB", m["by"])
    b.close()

lines = ["// Generated by the image download script. Photos: Pexels (free to use, pexels.com/license).", "import type { StaticImageData } from \"next/image\";"]
for slot in PICKS: lines.append(f'import {slot} from "@/assets/img/{slot}.jpg";')
lines.append("\ntype Img = { src: StaticImageData; alt: string };")
def entry(slot): return f'{{ src: {slot}, alt: {json.dumps(PICKS[slot][2])} }}'
lines.append("export const images: { hero: Img; about: Img; work: Img; donate: Img; gallery: Img[] } = {")
for s in ("hero", "about", "work", "donate"): lines.append(f"  {s}: {entry(s)},")
lines.append("  gallery: [" + ", ".join(entry(s) for s in PICKS if s.startswith("g")) + "],")
lines.append("};\n")
seen, credits = set(), []
for slot, (key, _, _) in PICKS.items():
    m = meta[key]
    if m["page"] in seen: continue
    seen.add(m["page"]); credits.append({"by": m["by"] or "Pexels contributor", "url": m["page"]})
lines.append("export const credits = " + json.dumps(credits, indent=2, ensure_ascii=False) + ";")
(SITE / "lib/images.ts").write_text("\n".join(lines) + "\n")
